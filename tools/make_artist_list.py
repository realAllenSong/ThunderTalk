"""Build Compose's offline artist names from Wikidata (CC0).

Run manually, never from the app. Select singers/musicians and bands ranked
by sitelinks, retaining English and Chinese labels. The JSON response cache
allows review and reproduction without another network request.
Source/licence: https://www.wikidata.org/wiki/Wikidata:Data_access
"""
from __future__ import annotations

import argparse
import json
import re
import time
import urllib.parse
import urllib.request
from pathlib import Path

ENDPOINT = "https://query.wikidata.org/sparql"
HEADERS = {"User-Agent": "ThunderTalk-artist-list/1.0 (https://github.com/realAllenSong/ThunderTalk)",
           "Accept": "application/sparql-results+json"}


def query(kind, limit):
    selector = ('VALUES ?occupation { wd:Q177220 wd:Q639669 wd:Q2252262 } '
                '?item wdt:P106 ?occupation .' if kind == 'people' else
                '?item wdt:P31/wdt:P279* wd:Q215380 .')
    return f'''SELECT ?item ?links ?en ?zh WHERE {{
      {{ SELECT DISTINCT ?item ?links WHERE {{ {selector}
         ?item wikibase:sitelinks ?links . FILTER(?links > 5)
      }} ORDER BY DESC(?links) ?item LIMIT {limit} }}
      OPTIONAL {{ ?item rdfs:label ?en . FILTER(LANG(?en) = "en") }}
      OPTIONAL {{ ?item rdfs:label ?zh . FILTER(LANG(?zh) = "zh") }}
    }} ORDER BY DESC(?links) ?item'''


def names_from(rows):
    names = set()
    for row in rows:
        for language in ('en', 'zh', 'zhHans', 'zhHant'):
            name = row.get(language, {}).get('value', '').strip()
            if len(name) >= 2 and not re.fullmatch(r'Q\d+', name) and '\n' not in name:
                names.add(name)
    return sorted(names, key=str.casefold)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--cache', type=Path, default=Path('artifacts/music-spike/artists-wikidata.json'))
    ap.add_argument('--output', type=Path, default=Path('assets/music/artists.txt'))
    ap.add_argument('--refresh', action='store_true')
    ap.add_argument('--limit', type=int, default=2500, help='entities per category')
    a = ap.parse_args()
    if a.cache.exists() and not a.refresh:
        data = json.loads(a.cache.read_text())
    else:
        rows = []
        for kind in ('people', 'bands'):
            url = ENDPOINT + '?' + urllib.parse.urlencode({'query': query(kind, a.limit), 'format': 'json'})
            req = urllib.request.Request(url, headers=HEADERS)
            with urllib.request.urlopen(req, timeout=90) as response:
                rows.extend(json.load(response)['results']['bindings'])
        data = {'retrieved_utc': time.strftime('%Y-%m-%d', time.gmtime()), 'rows': rows}
        a.cache.parent.mkdir(parents=True, exist_ok=True)
        a.cache.write_text(json.dumps(data, ensure_ascii=False, indent=2))
    if not data.get('chinese_variants'):
        ids = [row['item']['value'].rsplit('/', 1)[-1] for row in data['rows'] if row.get('zh')]
        variants = []
        for offset in range(0, len(ids), 50):
            params = {'action': 'wbgetentities', 'ids': '|'.join(ids[offset:offset + 50]),
                      'props': 'labels', 'languages': 'zh-hans|zh-hant', 'languagefallback': '1', 'format': 'json'}
            url = 'https://www.wikidata.org/w/api.php?' + urllib.parse.urlencode(params)
            with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), timeout=30) as response:
                result = json.load(response)
            for entity in result['entities'].values():
                labels = entity.get('labels', {})
                variants.append({'zhHans': labels.get('zh-hans', {}), 'zhHant': labels.get('zh-hant', {})})
        data['chinese_variants'] = variants
        a.cache.write_text(json.dumps(data, ensure_ascii=False, indent=2))
    names = names_from(data['rows'] + data['chinese_variants'])
    if len(names) < 100:
        raise RuntimeError('Refusing an incomplete artist list')
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text('# Wikidata labels (CC0); generated by tools/make_artist_list.py\n'
                        f'# Retrieved {data["retrieved_utc"]}; ranked by sitelinks\n'
                        '# https://www.wikidata.org/wiki/Wikidata:Data_access\n' + '\n'.join(names) + '\n')
    print(f'{len(names)} names from {len(data["rows"])} entities → {a.output}')


if __name__ == '__main__':
    main()
